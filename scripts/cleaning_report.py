"""Write the cleaning report for the corpus audit.

Every number in the report is computed here from two committed files:
    results/audit/corpus_audit_DATE.json     counts from scripts/audit_corpus.py
    results/audit/indian_check_DATE.csv      final label and evidence note per document

Output:
    results/audit/cleaning_report_DATE.md

The old corpus is not edited. The report records what it held and what the
scope rule (docs/decisions/0001-corpus-scope.md) keeps, so the rebuild can be
compared against it.

Usage:
    uv run python scripts/cleaning_report.py --date 2026-11-18
"""

import argparse
import csv
import hashlib
import json
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIT_DIR = ROOT / "results/audit"


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git_commit() -> str:
    run = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True)
    return run.stdout.strip()


def reason(row: dict) -> str:
    """Why a document ends up kept or dropped, in the words used in the report."""
    if row["final_label"] == "drop" and row["note"].startswith("duplicate"):
        return "drop: duplicate copy"
    if row["final_label"] == "drop":
        if row["proposed_label"] == "drop":
            return "drop: located in another country (Wikidata P17)"
        return "drop: subject is not Indian"
    if row["proposed_label"] == "keep":
        return "keep: located in India (Wikidata P17)"
    return "keep: Indian subject with no country in Wikidata"


def table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--date", required=True, help="audit date, as in the input file names")
    args = parser.parse_args()

    audit_path = AUDIT_DIR / f"corpus_audit_{args.date}.json"
    check_path = AUDIT_DIR / f"indian_check_{args.date}.csv"
    audit = json.loads(audit_path.read_text(encoding="utf-8"))
    rows = list(csv.DictReader(open(check_path, encoding="utf-8")))

    unlabelled = [r["title"] for r in rows if r["final_label"] not in ("keep", "drop")]
    if unlabelled:
        raise SystemExit(f"{len(unlabelled)} rows have no final_label, e.g. {unlabelled[:3]}")

    total = len(rows)
    final = Counter(r["final_label"] for r in rows)
    reasons = Counter(reason(r) for r in rows)
    review_rows = [r for r in rows if r["proposed_label"] == "review"]
    changed = [
        r
        for r in rows
        if r["proposed_label"] != "review"
        and r["final_label"] != r["proposed_label"]
        and not r["note"].startswith("duplicate")
    ]
    checked = [r for r in rows if r["author_checked"].strip().lower() == "yes"]
    checked_review = [r for r in review_rows if r["author_checked"].strip().lower() == "yes"]
    borderline = [r for r in rows if "BORDERLINE" in r["note"]]
    countries = Counter(
        r["countries"].split(" (")[0] for r in rows if reason(r) == "drop: located in another country (Wikidata P17)"
    )
    live, legacy = audit["live_corpus"], audit["legacy_corpus"]

    out = [
        f"# Corpus cleaning report, {args.date}",
        "",
        f"Generated by `scripts/cleaning_report.py` at commit `{git_commit()}` from:",
        "",
        f"- `{audit_path.relative_to(ROOT)}` (sha256 `{sha256_of(audit_path)[:16]}…`)",
        f"- `{check_path.relative_to(ROOT)}` (sha256 `{sha256_of(check_path)[:16]}…`)",
        "",
        f"The live corpus held {total} documents. Under the scope rule (Republic of India only,"
        f" decision 0001) {final['keep']} are kept and {final['drop']} are dropped.",
        "",
        "## Kept and dropped, by reason",
        "",
        *table(["Reason", "Documents"], [[k, v] for k, v in sorted(reasons.items())]),
        "",
        "## How each label was set",
        "",
        "- Each article's Wikidata item and country (P17) gave a proposed label: keep (India),"
        " drop (another present-day country) or review (no item, no country, or only historical states).",
        f"- {len(review_rows)} documents were proposed for review. Each was decided from the Wikidata"
        " item (citizenship P27, country of origin P495) and the Wikipedia article's opening sentences,"
        " and the evidence is in the note column.",
        f"- {len(changed)} documents with a keep or drop proposal ended with a different final label.",
        f"- {len(checked)} rows are marked as checked by the author, including"
        f" {len(checked_review)} of the {len(review_rows)} review rows.",
        "",
    ]
    if borderline:
        out += ["Borderline calls, flagged in the note column:", ""]
        out += [f"- {r['title']} ({r['final_label']}): {r['note']}" for r in borderline]
        out += [""]
    out += [
        "## Dropped for location, by country",
        "",
        *table(["Country", "Documents"], [[c, n] for c, n in countries.most_common()]),
        "",
        "## Other checks",
        "",
        f"- Duplicate groups: {live['duplicate_groups']} groups covering {live['documents_in_duplicate_groups']}"
        f" documents; one copy kept per group, {reasons['drop: duplicate copy']} copies dropped.",
        f"- Synthetic records: {live['synthetic']} in the live corpus; {legacy['synthetic']} of"
        f" {legacy['total']} in the retired file `legacy/data/balanced/balanced_documents.json`.",
        f'- Records with source "Unknown": {live["unknown_source"]} in the live corpus;'
        f" {legacy['unknown_source']} of {legacy['total']} in the retired file.",
        f"- Documents without a Wikidata item: {live['without_wikidata_item']}.",
        "",
        "## Kept documents",
        "",
        ", ".join(sorted(r["title"] for r in rows if r["final_label"] == "keep")) + ".",
        "",
    ]

    report_path = AUDIT_DIR / f"cleaning_report_{args.date}.md"
    report_path.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {report_path.relative_to(ROOT)}: {final['keep']} kept, {final['drop']} dropped")


if __name__ == "__main__":
    main()
